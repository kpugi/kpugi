"use client";

import React, { useMemo } from "react";

interface CampaignBriefRendererProps {
  content?: string | null;
  className?: string;
}

const KNOWN_HEADING_REGEX =
  /^(?:Campaign Overview|About This Campaign|Initiative Overview|Product Offer & Overview|App Launch Details|Campaign Mission|Creator Instructions|Creator Steps|Distribution & Action Steps|How to Amplify & Earn|How to Share & Earn|Creator Posting Instructions|Posting Rules & Payout Verification|Verification & Payout Rules|Posting & Verification Requirements|Posting Rules|Rules & Requirements|Submission & Verification Rules|Tips for Maximum Viral Views|Tips to Maximize Earnings & Views|Tips to Maximize Reach|Tips to Drive Signups & Views|Tips for Maximum Reach|Tips to Boost Your Conversion Views|Tips to Drive Installs & Views|Performance Tips|Tips & Best Practices|Key Deliverables|Requirements)(?::)?$/i;

/**
 * Safely sanitizes basic HTML string by removing script/iframe tags and on* event handlers
 */
function sanitizeHtml(html: string): string {
  if (!html) return "";
  return html
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/<iframe\b[^<]*(?:(?!<\/iframe>)<[^<]*)*<\/iframe>/gi, "")
    .replace(/<object\b[^<]*(?:(?!<\/object>)<[^<]*)*<\/object>/gi, "")
    .replace(/\son\w+="[^"]*"/gi, "")
    .replace(/\son\w+='[^']*'/gi, "")
    .replace(/\son\w+=\w+/gi, "");
}

/**
 * Auto-formats plain text or unsectioned HTML paragraphs into structured semantic HTML
 * with <h2> headings, <p> paragraphs, and <ul><li> lists.
 */
function autoFormatBrief(raw: string): string {
  if (!raw || !raw.trim()) return "";

  let text = raw.trim();

  // If the content already contains explicit semantic HTML (headings or lists), respect it directly
  const hasHeadings = /<h[1-6]\b[^>]*>/i.test(text);
  const hasLists = /<[ou]l\b[^>]*>/i.test(text);
  if (hasHeadings || hasLists) {
    // Strip redundant empty paragraphs generated by editors or line breaks
    return text.replace(/<p>\s*(?:<br\s*\/?>|&nbsp;)?\s*<\/p>/gi, "");
  }

  // If text is wrapped in <p> tags with no headings/lists, extract the text lines for re-sectioning
  if (/<p\b[^>]*>/i.test(text)) {
    text = text
      .replace(/<p\b[^>]*>(.*?)<\/p>/gi, "$1\n")
      .replace(/<br\s*\/?>/gi, "\n")
      .replace(/<[^>]+>/g, "")
      .trim();
  }

  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);

  const output: string[] = [];
  let inList: "ul" | "ol" | null = null;
  let currentSection = "";

  const closeList = () => {
    if (inList) {
      output.push(inList === "ol" ? "</ol>" : "</ul>");
      inList = null;
    }
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    // Check heading: ## Markdown, **Heading**, or known brief headings
    const mdHeading = line.match(/^#{1,3}\s+(.+)$/);
    const boldHeading = line.match(/^\*\*(.+?)\*\*:?$/);
    const isKnownHeading =
      KNOWN_HEADING_REGEX.test(line) ||
      (/^[A-Z][A-Za-z0-9\s&/-]{3,40}:$/.test(line) && !line.includes("."));

    if (mdHeading || boldHeading || isKnownHeading) {
      closeList();
      const title = (mdHeading ? mdHeading[1] : boldHeading ? boldHeading[1] : line)
        .replace(/\*\*/g, "")
        .replace(/:$/, "")
        .trim();
      currentSection = title.toLowerCase();
      output.push(`<h2>${title}</h2>`);
      continue;
    }

    // Check numbered items: 1. or 1)
    const numberedMatch = line.match(/^(\d+)[\.\)]\s+(.+)$/);
    if (numberedMatch) {
      if (inList !== "ol") {
        closeList();
        output.push("<ol>");
        inList = "ol";
      }
      const itemContent = numberedMatch[2].replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
      output.push(`<li>${itemContent}</li>`);
      continue;
    }

    // Check bullet items: • or - or *
    const bulletMatch = line.match(/^[•*-]\s+(.+)$/);
    const isRuleOrTipSection =
      (currentSection.includes("rule") ||
        currentSection.includes("tip") ||
        currentSection.includes("verification")) &&
      line.length < 160;

    if (bulletMatch || isRuleOrTipSection) {
      if (inList !== "ul") {
        closeList();
        output.push("<ul>");
        inList = "ul";
      }
      const rawBulletText = bulletMatch ? bulletMatch[1] : line;
      const itemContent = rawBulletText.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
      output.push(`<li>${itemContent}</li>`);
      continue;
    }

    closeList();
    const pContent = line.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
    output.push(`<p>${pContent}</p>`);
  }

  closeList();
  return output.join("\n");
}

/**
 * CampaignBriefRenderer renders formatted HTML briefs or automatically sections plain text
 * with headers, paragraphs, and list hierarchies.
 */
export default function CampaignBriefRenderer({
  content,
  className = "",
}: CampaignBriefRendererProps) {
  const raw = (content || "").trim();

  const formattedHtml = useMemo(() => {
    if (!raw) return "";
    const structured = autoFormatBrief(raw);
    return sanitizeHtml(structured);
  }, [raw]);

  if (!raw) {
    return (
      <p className={`text-sm text-slate-400 dark:text-slate-500 italic ${className}`}>
        No campaign brief description provided.
      </p>
    );
  }

  return (
    <div
      className={`campaign-brief-content prose dark:prose-invert prose-slate max-w-none text-sm sm:text-base leading-relaxed text-slate-700 dark:text-slate-300
        prose-headings:font-display prose-headings:font-extrabold prose-headings:text-slate-900 dark:prose-headings:text-white
        prose-h2:text-base sm:prose-h2:text-lg prose-h2:mt-6 prose-h2:mb-2 prose-h2:pb-1.5 prose-h2:border-b prose-h2:border-slate-100 dark:prose-h2:border-white/10 prose-h2:tracking-tight
        prose-h3:text-sm sm:prose-h3:text-base prose-h3:mt-4 prose-h3:mb-1.5
        prose-p:my-2.5 prose-p:leading-relaxed prose-p:text-slate-600 dark:text-slate-300
        prose-ul:my-2.5 prose-ul:list-disc prose-ul:pl-5 prose-ul:space-y-1.5
        prose-ol:my-2.5 prose-ol:list-decimal prose-ol:pl-5 prose-ol:space-y-1.5
        prose-li:leading-relaxed prose-li:text-slate-700 dark:text-slate-300
        prose-strong:font-bold prose-strong:text-slate-900 dark:prose-strong:text-white
        prose-blockquote:border-l-4 prose-blockquote:border-indigo-500 prose-blockquote:bg-indigo-50/50 dark:prose-blockquote:bg-indigo-950/20 prose-blockquote:py-2 prose-blockquote:px-4 prose-blockquote:rounded-r-xl prose-blockquote:italic prose-blockquote:my-3
        prose-a:text-indigo-600 dark:prose-a:text-indigo-400 prose-a:underline hover:prose-a:text-indigo-700
        prose-code:text-indigo-600 dark:prose-code:text-indigo-300 prose-code:bg-indigo-50 dark:prose-code:bg-indigo-950/40 prose-code:px-1.5 prose-code:py-0.5 prose-code:rounded prose-code:font-mono prose-code:text-xs
        ${className}`}
      dangerouslySetInnerHTML={{ __html: formattedHtml }}
    />
  );
}
